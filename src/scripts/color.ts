// Outils couleur : contraste WCAG pour choisir automatiquement
// un texte noir ou blanc cassé sur la couleur de chaque bière.

export const INK = '#111110';
export const PAPER = '#F7F3EA';

function channel(c: number): number {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
}

export function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '');
  const n = parseInt(h.length === 3 ? h.replace(/./g, (c) => c + c) : h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

export function luminance(hex: string): number {
  const [r, g, b] = hexToRgb(hex);
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

export function contrast(a: string, b: string): number {
  const la = luminance(a);
  const lb = luminance(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}

/** Renvoie la couleur de texte (encre ou papier) la plus lisible sur `bg`. */
export function textOn(bg: string): string {
  return contrast(bg, INK) >= contrast(bg, PAPER) ? INK : PAPER;
}
